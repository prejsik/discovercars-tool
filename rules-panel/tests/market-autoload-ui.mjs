import assert from 'node:assert/strict';
import { chromium } from '../../node_modules/playwright/index.mjs';
import { strToU8 } from 'fflate';
import { loadPriceContext,loadPriceSource } from '../server/reports.mjs';
const origin=process.env.PANEL_URL??'http://127.0.0.1:4317';
const browser=await chromium.launch({headless:true});const context=await browser.newContext();const page=await context.newPage();
const errors=[];page.on('pageerror',error=>errors.push(error.message));const writes=[];page.on('request',r=>{if(r.method()==='POST')writes.push(r.url());});
try {
  await page.clock.setFixedTime(new Date('2026-11-03T13:00:00Z'));
  const snapshot=await(await context.request.get(`${origin}/policy-snapshot.json`)).json();
  const labels=['Krakow Airport (KRK)',...Array.from({length:24},(_,i)=>`Test City ${i+1}`)];
  const values=['Other (8)','','90,00 PLN/d','','','MM Cars Rental (8)','','60,00 PLN/d','','','Brak oferty','60,00 PLN/d','','Top 1','0','',false];
  const scenarios=Array.from({length:45},(_,i)=>Array.from({length:13},(_,j)=>({date:new Date(Date.UTC(2026,10,4+i)).toISOString().slice(0,10),duration:String(j+2),rows:labels.map(label=>[label,'airport',values,values]),errors:[]}))).flat();
  const bytes=strToU8(`<script type="application/json" id="report-data">${JSON.stringify({scenarios})}</script>`);
  const hash=Buffer.from(await crypto.subtle.digest('SHA-256',bytes)).toString('hex');
  const manifest={run_id:'123',git_sha:'a'.repeat(40),generated_at:'2026-11-03T12:00:00Z',source_started_at:'2026-11-03T09:00:00Z',start_dates:[...new Set(scenarios.map(s=>s.date))],durations:Array.from({length:13},(_,i)=>i+2),status:'success',report_html_sha256:hash};
  const fetcher=async url=>url.endsWith('run-manifest.json')?Response.json(manifest):new Response(bytes);
  const repository={json:async()=>({locations:labels.map(label=>({scraper_label:label,zones:label.startsWith('Krakow')?['KRLO']:[]}))})};
  const meta=await loadPriceContext({mode:'market',reportRunId:'123'},repository,fetcher);
  let failed=true;let reads=0;
  await page.route('**/api/workspace',r=>r.fulfill({json:{snapshot,capabilities:{publish:false},draft:null,history:[],status:{report:meta.report}}}));
  await context.route(/\/api\/report\/(prices|price-source)\?/,async route=>{
    reads++;if(failed)return route.fulfill({status:502,json:{error:'Test: brak połączenia z raportem'}});
    const query=Object.fromEntries(new URL(route.request().url()).searchParams);
    assert.equal(query.mode,'market','Only the existing market report is read automatically');
    const body=query.kind?await loadPriceSource(query,repository,fetcher):JSON.stringify(await loadPriceContext(query,repository,fetcher));
    return route.fulfill({body:typeof body==='string'?body:Buffer.from(body),contentType:query.kind?'application/octet-stream':'application/json'});
  });
  await page.goto(`${origin}/?view=prices`);
  await page.getByRole('alert').filter({hasText:'Test: brak połączenia'}).waitFor();
  assert.equal(reads,1,'A failed automatic read does not loop');
  failed=false;const started=performance.now();
  await page.getByRole('button',{name:'Pokaż ceny',exact:true}).click();
  await page.locator('.attention-map tbody tr').nth(24).waitFor({timeout:60000});
  for(const width of [1440,1024,390,320]){
   await page.setViewportSize({width,height:1000});
   assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'map overflow '+width);
   if(width===390||width===1440)await page.screenshot({path:'docs/ui-redesign-3/verification/stage-2-'+width+'.png',fullPage:true});
  }
  await page.getByRole('button',{name:'Tabela oddziałów',exact:true}).click();
  await page.locator('.attention-table tbody tr').nth(24).waitFor({timeout:60000});
  await page.getByRole('tab',{name:'Wykres',exact:true}).click();
  await page.locator('.market-chart').waitFor({timeout:60000});
  const elapsed=Math.round(performance.now()-started);const loadedReads=reads;
  await page.getByRole('tab',{name:'Do sprawdzenia',exact:true}).click();
  await page.locator('.attention-table tbody tr').nth(24).waitFor();
  assert.equal(await page.locator('.attention-table tbody tr').count(),25);
  await page.getByRole('button',{name:'Sprawdź oddział',exact:true}).first().click();
  await page.locator('.attention-view').getByLabel('Start od',{exact:true}).fill('2026-11-04');
  await page.locator('.attention-view').getByLabel('Start do',{exact:true}).fill('2026-12-18');
  assert.equal(await page.locator('.band-date').count(),20);
  await page.getByRole('button',{name:'Pokaż kolejne 20 dat',exact:true}).click();
  assert.equal(await page.locator('.band-date').count(),40);
  await page.getByRole('button',{name:'Pulpit',exact:true}).click();
  await page.getByRole('button',{name:'Ceny i rynek',exact:true}).click();
  assert.equal(reads,loadedReads,'Returning to the panel reuses the loaded report');
  assert.equal(await page.locator('.band-date').count(),40,'Expanded group and pagination survive navigation');
  await page.locator('.attention-view').getByRole('combobox',{name:'Skrzynia w przeglądzie',exact:true}).selectOption('automatic');
  await page.getByRole('tab',{name:'Wykres',exact:true}).click();
  assert.equal(await page.locator('.chart-filters').getByRole('combobox',{name:'Skrzynia',exact:true}).inputValue(),'all','Overview does not change chart filters');
  await page.getByRole('tab',{name:'Do sprawdzenia',exact:true}).click();
  assert.equal(await page.locator('.attention-view').getByRole('combobox',{name:'Skrzynia w przeglądzie',exact:true}).inputValue(),'automatic','Overview preserves its own selections');
  await page.getByRole('button',{name:'Pulpit',exact:true}).click();
  assert.equal(await page.locator('.counter-strip').count(),0,'No duplicated dashboard counters');
  const beforeDashboardClick=reads;
  await page.locator('.operations-dashboard').getByRole('button',{name:'Przejrzyj ceny',exact:true}).click();
  await page.locator('.attention-view').waitFor();
  assert.equal(reads,beforeDashboardClick,'Dashboard link reuses loaded prices');
  assert.deepEqual(writes,[]);assert.deepEqual(errors,[]);
  console.log(`Auto-load UI PASS: retry, no loops/duplicate reads/writes, 25 locations, 2-14 durations, bounded rows. Synthetic report ${(bytes.length/1e6).toFixed(2)} MB loaded in ${elapsed} ms locally.`);
} finally {await browser.close();}
